// Prints the AviUtl2 SDK struct layouts that aviutl2.zig mirrors by hand, as Zig source.
// `zig build sdk-check` builds this against a local SDK checkout, runs it, and compares the
// output with aviutl2_layout.zig.
#include <windows.h>
#include <d3d11.h>
#include <dwrite.h>
#include <cstddef>
#include <cstdint>
#include <cstdio>
using std::int64_t;
#include "filter2.h"

#define SIZE(type) std::printf("pub const %s_size = %u;\n", #type, (unsigned)sizeof(type))
#define OFFSET(type, field) std::printf("pub const %s_%s = %u;\n", #type, #field, (unsigned)offsetof(type, field))

int main() {
    std::printf("//! Generated by tools/sdk_layout_probe.cpp; do not edit. Regenerate with `zig build sdk-check`.\n\n");
    OFFSET(OBJECT_INFO, frame);
    OFFSET(OBJECT_INFO, time);
    OFFSET(OBJECT_INFO, width);
    OFFSET(OBJECT_INFO, height);
    OFFSET(FILTER_PROC_VIDEO, scene);
    OFFSET(FILTER_PROC_VIDEO, object);
    OFFSET(FILTER_PROC_VIDEO, get_image_data);
    OFFSET(FILTER_PROC_VIDEO, set_image_data);
    SIZE(PIXEL_RGBA);
    SIZE(FILTER_ITEM_TRACK);
    OFFSET(FILTER_ITEM_TRACK, value);
    OFFSET(FILTER_ITEM_TRACK, zero_display);
    OFFSET(FILTER_ITEM_TRACK, slider_ratio);
    SIZE(FILTER_ITEM_SELECT);
    OFFSET(FILTER_ITEM_SELECT, value);
    OFFSET(FILTER_ITEM_SELECT, list);
    std::printf("pub const FILTER_ITEM_SELECT_ITEM_size = %u;\n", (unsigned)sizeof(FILTER_ITEM_SELECT::ITEM));
    SIZE(FILTER_ITEM_FILE);
    OFFSET(FILTER_ITEM_FILE, value);
    OFFSET(FILTER_ITEM_FILE, filefilter);
    SIZE(FILTER_PLUGIN_TABLE);
    OFFSET(FILTER_PLUGIN_TABLE, items);
    OFFSET(FILTER_PLUGIN_TABLE, func_proc_video);
    OFFSET(FILTER_PLUGIN_TABLE, func_proc_audio);
    return 0;
}
